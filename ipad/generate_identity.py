#!/usr/bin/env python3
"""Write the native runtime's identity header from the verified generated code.

Only hashes and versions go into the header (no host paths): the exact Windows modules and
master files the generated code was built from, the gen manifest, the prebuilt device
dependencies and this worktree's commit. ipad/native_bridge.mm validates the in-app
Documents/Skyrim against it and logs it at launch.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "macos"))
from inputs import verify_generated  # noqa: E402


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("generated", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--game-dir", type=Path, help="game folder gen/ is bound to (default: the one its manifest records)")
    args = parser.parse_args()
    receipt = verify_generated(args.generated, args.game_dir)
    modules = {name: value["sha256"] for name, value in receipt["modules"].items()}
    essential = {name: value["sha256"] for name, value in receipt["essential_data"].items()}
    moltenvk = json.loads((ROOT / "ipad/deps/MoltenVK-ios-v1.4.2/receipt.json").read_text())
    ffmpeg = json.loads((ROOT / "ipad/deps/ffmpeg-iphoneos/build-manifest.json").read_text())
    try:
        commit = subprocess.check_output(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
                                         text=True, stderr=subprocess.DEVNULL).strip()
    except (OSError, subprocess.CalledProcessError):
        commit = "unknown (not a git checkout)"
    identity = {
        "schema": 1,
        "platform": "iphoneos arm64",
        "generated_manifest_sha256": sha256(args.generated / "input-manifest.json"),
        "source_commit": commit,
        "moltenvk": {"release": "v1.4.2", "library_sha256": moltenvk["library_sha256"]},
        "ffmpeg": {"version": ffmpeg["version"], **{k: v["sha256"] for k, v in ffmpeg["archives"].items()}},
        "modules": modules,
        "essential_data": essential,
    }
    lines = ["/* Generated by ipad/generate_identity.py; do not edit. Hashes only, no host paths. */",
             "#pragma once",
             f"#define SKYRIM_NATIVE_IDENTITY_JSON {c_string(json.dumps(identity, separators=(',', ':')))}",
             "struct skyrim_native_file { const char *name; const char *sha256; };",
             "static const skyrim_native_file skyrim_native_modules[] = {"]
    lines += [f"    {{{c_string(n)}, {c_string(h)}}}," for n, h in sorted(modules.items())]
    lines += ["};", "static const skyrim_native_file skyrim_native_essential_data[] = {"]
    lines += [f"    {{{c_string(n)}, {c_string(h)}}}," for n, h in sorted(essential.items())]
    lines += ["};", ""]
    text = "\n".join(lines)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_text() != text:
        args.output.write_text(text)
    print(json.dumps({k: identity[k] for k in ("generated_manifest_sha256", "source_commit")}))


if __name__ == "__main__":
    main()
